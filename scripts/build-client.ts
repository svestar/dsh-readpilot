import { build } from 'esbuild'
import { writeFile } from 'node:fs/promises'

const result = await build({
  entryPoints: ['src/client/index.ts'],
  bundle: true,
  write: false,
  format: 'iife',
  globalName: '__dshReaderBundle',
  platform: 'browser',
  target: 'es2022',
  charset: 'utf8',
  legalComments: 'none',
  logLevel: 'info',
  footer: {
    js: "/* Generated by scripts/build-client.ts; source in src/client/. */\nwindow.__ModuleLoader__.load({ id: 'dsh-reader', factory(require) { return __dshReaderBundle.create(require) } })",
  },
})

const output = result.outputFiles?.[0]
if (!output) throw new Error('esbuild produced no output')
await writeFile('client.js', `${output.text}\n`, 'utf8')
console.log('built client.js')
