import { React } from '../../runtime.ts'
import type { StateSetter } from '../../runtime.ts'
import { messageOf } from '../../lib/helpers.ts'
import { parseReaderJumpUrl } from '../../../shared/jump-url.ts'
import type { ReaderJumpTarget } from '../../../shared/jump-url.ts'
import type { CallRpc, Screen, SelectChapter, TextFn } from '../../lib/types.ts'

interface ChatJumpOptions {
  call: CallRpc
  screen: Screen
  t: TextFn
  selectChapter: SelectChapter
  setChatError: StateSetter<string>
  setChatOpen: StateSetter<boolean>
  openOtherBook?: (target: ReaderJumpTarget) => void
}

/** Intercept citations generated by the companion as structured reader links. */
export function useChatJump({
  call,
  screen,
  t,
  selectChapter,
  setChatError,
  setChatOpen,
  openOtherBook,
}: ChatJumpOptions) {
  const jumpingRef = React.useRef(false)

  const jumpToTarget = React.useCallback(async (target: ReaderJumpTarget) => {
    if (screen.kind !== 'book' || jumpingRef.current) return
    if (target.bookId !== screen.detail.book.id) {
      if (openOtherBook) {
        openOtherBook(target)
        return
      }
      setChatError(t('chatJumpOtherBook'))
      return
    }
    jumpingRef.current = true
    setChatError('')
    try {
      let chapterId = target.chapterId
      let offset = target.offset
      if (offset === undefined && target.q) {
        const result = await call('search', { bookId: target.bookId, query: target.q, limit: 20 })
        const match = result.matches.find((item: any) => item.chapterId === chapterId)
        if (!match) {
          setChatError(t('chatJumpNotFound'))
          return
        }
        chapterId = match.chapterId
        offset = match.offset
      }
      await selectChapter(target.bookId, chapterId, { offset, flash: true })
      if (typeof window !== 'undefined' && window.innerWidth <= 1100) setChatOpen(false)
    } catch (cause) {
      setChatError(`${t('chatJumpFailed')}：${messageOf(cause)}`)
    } finally {
      jumpingRef.current = false
    }
  }, [call, screen, selectChapter, setChatError, setChatOpen, t, openOtherBook])

  React.useEffect(() => {
    if (screen.kind !== 'book' || typeof document === 'undefined') return
    const onLinkClick = (event: any) => {
      const anchor = event.target?.closest?.('a[href*="dsh-readpilot.invalid/jump"]')
      if (!anchor) return
      const target = parseReaderJumpUrl(anchor.href)
      if (!target) return
      event.preventDefault()
      event.stopImmediatePropagation()
      void jumpToTarget(target)
    }
    document.addEventListener('click', onLinkClick, true)
    return () => document.removeEventListener('click', onLinkClick, true)
  }, [jumpToTarget, screen.kind])
}
